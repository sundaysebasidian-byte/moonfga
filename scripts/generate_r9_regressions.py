"""Embed actual pinned OpenFGA Check outcomes for r9 review cases."""
import argparse
import json
from pathlib import Path


def main():
    p=argparse.ArgumentParser();p.add_argument('directory',type=Path);a=p.parse_args()
    cases=json.loads((a.directory/'cases.json').read_text())
    expected=json.loads((a.directory/'expected.json').read_text())
    assert len(cases)==len(expected)
    assert not json.loads((a.directory/'mismatches.json').read_text())
    rows=[]
    for c,e in zip(cases,expected):
        condition=c['model']['conditions']['cel_condition']
        result=e['check']
        result=result if isinstance(result,str) else str(result).lower()
        row=[condition['expression'],json.dumps(c['context'],ensure_ascii=False),result,json.dumps(condition['parameters'])]
        rows.append('    ('+', '.join(json.dumps(v,ensure_ascii=False) for v in row)+'),')
    lines=['// OpenFGA v1.22.1 r9 outcomes; generated by scripts/generate_r9_regressions.py.']
    for start in range(0,len(rows),256):
        lines+=['///|',f'test "r9 official API outcomes {start//256+1}" {{','  oracle_cases([']+rows[start:start+256]+['  ])','}']
    Path('cel/r9_oracle_test.mbt').write_text('\n'.join(lines)+'\n')
    print(f'embedded {len(rows)} r9 model/evaluation outcomes')

if __name__=='__main__':main()
