"""Embed actual official condition outcomes for offline cross-backend tests."""
import argparse
import json
from pathlib import Path


def main():
    p = argparse.ArgumentParser()
    p.add_argument('directory', type=Path)
    args = p.parse_args()
    cases = json.loads((args.directory / 'cases.json').read_text())
    expected = json.loads((args.directory / 'expected.json').read_text())
    assert len(cases) == len(expected)
    records = []
    for c, e in zip(cases, expected):
        result = e['check']
        result = result if isinstance(result, str) else str(result).lower()
        condition = c['model']['conditions']['cel_condition']
        record = [condition['expression'], json.dumps(c.get('context', {}), ensure_ascii=False), result, json.dumps(condition['parameters'])]
        records.append('    (' + ', '.join(json.dumps(v, ensure_ascii=False) for v in record) + '),')
    lines = ['// Official OpenFGA v1.22.1 outcomes; generated by scripts/generate_cel_regressions.py.']
    for start in range(0, len(records), 256):
        lines += ['///|', f'test "official CEL model and evaluation outcomes {start // 256 + 1}" {{', '  oracle_cases([']
        lines += records[start:start + 256]
        lines += ['  ])', '}']
    lines += ['''
///|
fn oracle_cases(cases : Array[(String, String, String, String)]) -> Unit raise {
  for (source, context, expected, params_json) in cases {
    let params : Array[@fga.ConditionParam] = []
    match @json.parse(params_json) {
      Object(m) => m.each((name, value) => {
        let (base, inner) = oracle_parameter(value)
        params.push({name, type_name:base, generic_type:inner})
      })
      _ => abort("bad parameter fixture")
    }
    let condition : @fga.Condition = {name:"cel_condition", expression:source, parameters:params}
    let valid = try { @cel.check_condition(condition); true } catch { _ => false }
    let actual = if @utf8.encode(source[:]).length() > 512 { "M:validation_error" }
      else if !valid { "M:invalid_authorization_model" }
      else {
        try {
          let fields = match @json.parse(context) { Object(m) => m; _ => abort("invalid fixture context") }
          @cel.eval_condition(condition, fields).to_string()
        } catch { _ => "E2000" }
      }
    assert_eq(actual, expected, msg=source + " context=" + context)
  }
}

///|
fn oracle_parameter(value : Json) -> (String, String?) {
  let name = @fga.json_get_string(value,"type_name").unwrap()
  let base = match name {
    "TYPE_NAME_INT" => "int"; "TYPE_NAME_UINT" => "uint"; "TYPE_NAME_DOUBLE" => "double"
    "TYPE_NAME_ANY" => "any"; "TYPE_NAME_LIST" => "list"; "TYPE_NAME_MAP" => "map"
    "TYPE_NAME_STRING" => "string"; "TYPE_NAME_BOOL" => "bool"
    "TYPE_NAME_TIMESTAMP" => "timestamp"; "TYPE_NAME_DURATION" => "duration"
    _ => abort("unsupported fixture type")
  }
  let generics = @fga.json_get_array(value,"generic_types")
  if generics.length() > 1 { return (base, Some("!invalid")) }
  let inner = if generics.is_empty() { None } else {
    let (b,t) = oracle_parameter(generics[0])
    Some(b + (match t { None => ""; Some(t) => "<" + t + ">" }))
  }
  (base,inner)
}
''']
    Path('cel/oracle_test.mbt').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
